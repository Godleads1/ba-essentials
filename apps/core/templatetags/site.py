_SOCIAL_LABELS = (
    ("linkedin", "LinkedIn"),
    ("x", "X"),
    ("instagram", "Instagram"),
    ("facebook", "Facebook"),
    ("youtube", "YouTube"),
)


@register.simple_tag
def icon(name: str, css_class: str = "h-4 w-4", solid: bool = False):
    """Render a decorative inline SVG icon. Unknown names render nothing."""
    if solid or name not in _LINE_ICONS:
        body = _SOLID_ICONS.get(name)
        if body is None:
            return ""
        return format_html(
            '<svg class="{}" viewBox="0 0 24 24" fill="currentColor" '
            'aria-hidden="true" focusable="false">{}</svg>',
            css_class,
            mark_safe(body),  # noqa: S308 - static, module-level markup
        )
    return format_html(
        '<svg class="{}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
        'aria-hidden="true" focusable="false">{}</svg>',
        css_class,
        mark_safe(_LINE_ICONS[name]),  # noqa: S308 - static, module-level markup
    )


@register.simple_tag
def social_links():
    """Social profiles as (key, label, url), in display order.

    Every profile is listed so the footer keeps its full row of icons. The url
    is empty until settings.SOCIAL_LINKS has one, and the template renders an
    unlinked icon in that case so the footer never carries a dead link.
    """
    configured = getattr(settings, "SOCIAL_LINKS", {}) or {}
    return [(key, label, configured.get(key) or "") for key, label in _SOCIAL_LABELS]
